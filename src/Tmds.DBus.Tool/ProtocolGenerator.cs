    enum Accessibility
    {
        NotApplicable,
        Public,
        Internal,
        Private,
        Protected
    }

    class ProtocolGeneratorSettings
    {
        public string? ServiceName { get; set; }
        public Accessibility TypesAccessModifier = Accessibility.NotApplicable;
        public string? GeneratorDescription { get; set; }
        public string DBusHandlerTypeName { get; set; } = "Tmds.DBus.Protocol.DBusHandler";
    }

    class ProtocolGenerator : IGenerator
    {
        private readonly ProtocolGeneratorSettings _settings;
        private readonly StringBuilder _sb = new();
        private readonly Dictionary<string, (bool, Argument[])> _messageReadMethods = new();
        private readonly Dictionary<string, string> _typeReadMethods = new();
        private readonly Dictionary<string, (bool, string)> _typeWriteMethods = new();
        private readonly List<(string Namespace, string InterfaceName, string HandlerInterfaceName)> _generatedHandlers = new();
        private readonly HashSet<string> _allInterfaces = new();
        private readonly Dictionary<string, XElement> _interfaceXmls = new();
        private readonly HashSet<string> _interfacesWithProperties = new();
        private bool _anyHandlerPublic;
        private int _indentation = 0;

        // Fully-qualified name prefixes for generated code.
        private const string _proto = "global::Tmds.DBus.Protocol";
        private const string _task = "global::System.Threading.Tasks.Task";
        private const string _vtask = "global::System.Threading.Tasks.ValueTask";
        private const string _action = "global::System.Action";
        private const string _func = "global::System.Func";
        private const string _idisposable = "global::System.IDisposable";
        private const string _syncCtx = "global::System.Threading.SynchronizationContext";

        public ProtocolGenerator(ProtocolGeneratorSettings settings)
        {
            _settings = settings;
        }

        private string AccessModifier(bool isPublic) => isPublic ? "public " : "";

        private string HandlerTypeNameFull => _settings.DBusHandlerTypeName;

        private (string Namespace, string ClassName) SplitHandlerTypeName()
        {
            int lastDot = HandlerTypeNameFull.LastIndexOf('.');
            return (HandlerTypeNameFull.Substring(0, lastDot), HandlerTypeNameFull.Substring(lastDot + 1));
        }

        private string HandlerTypeRef => $"global::{SplitHandlerTypeName().Namespace}.{SplitHandlerTypeName().ClassName}";

        private void StartBlock()
        {
            AppendLine("{");
            _indentation++;
        }

        private void EndBlock()
        {
            _indentation--;
            AppendLine("}");
        }

        private void AppendLine(string line)
        {
            if (line.Length == 0)
            {
                return;
            }
            if (line.Length != 0)
            {
                _sb.Append(' ', _indentation * 4);
            }
            _sb.AppendLine(line);
        }

        public string Generate(string ns, IEnumerable<InterfaceDescription> interfaceDescriptions)
        {
            _sb.Clear();

            if (!string.IsNullOrEmpty(_settings.GeneratorDescription))
            {
                AppendLine($"// Generated by {_settings.GeneratorDescription}");
            }
            AppendLine("// <auto-generated/>");
            AppendLine("#nullable enable");

            AppendLine($"namespace {ns}");
            StartBlock();

            bool anyProxies = false;
            bool anyProxyPublic = false;
            foreach (var interf in interfaceDescriptions)
            {
                try
                {
                    AppendPropertyTypes(interf.Name, interf.InterfaceXml, interf.GenerateProxy, interf.GenerateHandler, interf.IsProxyPublic, interf.IsHandlerPublic);
                    if (interf.GenerateProxy)
                    {
                        AppendProxyClass(interf.Name, interf.InterfaceXml, interf.IsProxyPublic);
                        anyProxies = true;
                        anyProxyPublic |= interf.IsProxyPublic;
                    }
                    if (interf.GenerateHandler)
                    {
                        AppendHandlerTypesForInterface(ns, interf.Name, interf.HandlerName, interf.InterfaceXml, interf.IsHandlerPublic);
                        AppendSignalsClass(interf.Name, interf.InterfaceXml, interf.IsHandlerPublic);
                        _anyHandlerPublic |= interf.IsHandlerPublic;
                    }
                }
                catch (Exception ex)
                {
                    throw new InterfaceGenerationException(interf, ex);
                }
            }

            if (anyProxies)
            {
                AppendServiceClass(interfaceDescriptions.Where(i => i.GenerateProxy), anyProxyPublic);
            }

            AppendReaderClass();
            AppendMessageWriterExtensionsClass();

            EndBlock();

            return _sb.ToString();
        }

        public string GenerateShared()
        {
            _sb.Clear();
            if (!string.IsNullOrEmpty(_settings.GeneratorDescription))
            {
                AppendLine($"// Generated by {_settings.GeneratorDescription}");
            }
            AppendLine("// <auto-generated/>");
            AppendLine("#nullable enable");

            var (handlerNamespace, handlerClassName) = SplitHandlerTypeName();

            AppendLine($"namespace {handlerNamespace}");
            StartBlock();

            // Add IIntrospectable to the generated handlers list for switch statement
            // Note: IIntrospectable is now handled directly in DBusHandler, not as a separate interface
            _generatedHandlers.Add((handlerNamespace, "org.freedesktop.DBus.Introspectable", "IIntrospectable"));

            AppendLine($"{AccessModifier(_anyHandlerPublic)}abstract class {handlerClassName} : {_proto}.IPathMethodHandler");
            StartBlock();

            var allInterfaces = _allInterfaces.OrderBy(x => x).ToList();

            // Generate DBusInterface Flags enum inside DBusHandler
            AppendLine("// Identifies the D-Bus interfaces. Used with SupportsInterface to filter interfaces per path.");
            AppendLine("[global::System.Flags]");
            AppendLine($"{(_anyHandlerPublic ? "protected" : "public")} enum DBusInterface");
            StartBlock();
            // Add Introspectable interface as first item
            AppendLine("// OrgFreedesktopDBusIntrospectable = 1,");
            int flagValue = 2;
            foreach (var interfaceName in allInterfaces)
            {
                string enumName = InterfaceNameToEnumValueName(interfaceName);
                AppendLine($"{enumName} = {flagValue},");
                flagValue *= 2;
            }
            EndBlock();
            AppendLine("");

            // Generate ReadOnlyMemory<byte> properties for introspection XML
            foreach (var interfaceName in allInterfaces)
            {
                if (_interfaceXmls.TryGetValue(interfaceName, out var xml))
                {
                    string enumName = InterfaceNameToEnumValueName(interfaceName);
                    AppendLine($"private static global::System.ReadOnlyMemory<byte> {enumName}Xml {{ get; }} =");
                    _indentation++;
                    AppendLine("\"\"\"");

                    // Create minimal version of XML (remove annotations, docstrings, etc.)
                    var minimalXml = MinimizeInterfaceXml(xml);

                    // Write the XML content (without declaration, with nice formatting)
                    var settings = new System.Xml.XmlWriterSettings
                    {
                        Indent = true,
                        IndentChars = "  ",
                        OmitXmlDeclaration = true,
                        NewLineChars = "\n"
                    };
                    using (var stringWriter = new System.IO.StringWriter())
                    using (var xmlWriter = System.Xml.XmlWriter.Create(stringWriter, settings))
                    {
                        minimalXml.WriteTo(xmlWriter);
                        xmlWriter.Flush();
                        var lines = stringWriter.ToString().Split('\n');
                        foreach (var line in lines)
                        {
                            if (line.Length > 0)
                            {
                                AppendLine(line);
                            }
                        }
                    }
                    _sb.AppendLine();
                    AppendLine("\"\"\"u8.ToArray();");
                    _indentation--;
                    AppendLine("");
                }
            }

            AppendLine("private readonly global::System.Threading.SendOrPostCallback? _postDelegate;");
            AppendLine("");

            // Add private const for OrgFreedesktopDBusIntrospectable
            AppendLine("private const DBusInterface OrgFreedesktopDBusIntrospectable = (DBusInterface)1;");
            AppendLine("");

            // Generate InterfacesWithProperties const
            var interfacesWithPropertiesFlags = new List<string>();
            foreach (var interfaceName in allInterfaces)
            {
                if (_interfacesWithProperties.Contains(interfaceName))
                {
                    string enumName = InterfaceNameToEnumValueName(interfaceName);
                    interfacesWithPropertiesFlags.Add($"DBusInterface.{enumName}");
                }
            }

            if (interfacesWithPropertiesFlags.Any())
            {
                AppendLine($"private const DBusInterface InterfacesWithProperties = {string.Join(" | ", interfacesWithPropertiesFlags)};");
                AppendLine("");
            }
            else
            {
                AppendLine("private const DBusInterface InterfacesWithProperties = 0;");
                AppendLine("");
            }

            AppendLine("public string Path { get; }");
            AppendLine("public bool HandlesChildPaths { get; }");
            AppendLine($"public {_proto}.DBusConnection Connection {{ get; }}");
            AppendLine("// The SynchronizationContext on which method handlers are invoked.");
            AppendLine($"protected {_syncCtx}? SynchronizationContext {{ get; }}");
            AppendLine("");
            AppendLine($"protected {handlerClassName}({_proto}.DBusConnection connection, string path, bool handlesChildPaths, bool handleOnCapturedContext = true)");
            AppendLine($"    : this(connection, path, handlesChildPaths, handleOnCapturedContext ? {_syncCtx}.Current : null)");
            StartBlock();
            EndBlock();
            AppendLine("");
            AppendLine($"protected {handlerClassName}({_proto}.DBusConnection connection, string path, bool handlesChildPaths, {_syncCtx}? synchronizationContext)");
            StartBlock();
            AppendLine("Connection = connection;");
            AppendLine("Path = path;");
            AppendLine("HandlesChildPaths = handlesChildPaths;");
            AppendLine("SynchronizationContext = synchronizationContext;");
            AppendLine("if (synchronizationContext is not null)");
            StartBlock();
            AppendLine("_postDelegate = state =>");
            StartBlock();
            AppendLine($"{_proto}.MethodContext context = ({_proto}.MethodContext)state!;");
            AppendLine("DBusInterface dbusInterface = ParseInterface(context);");
            AppendLine("DBusMethod method = FindMethodHandler(context, dbusInterface);");
            AppendLine("_ = InvokeAndDisposeAsync(method, context);");
            _indentation--;
            AppendLine("};");
            EndBlock();
            EndBlock();

            AppendLine("// Override to add cross-cutting logic (e.g. logging, error handling) around method invocations.");
            AppendLine($"protected virtual async {_vtask} InvokeAsync(DBusMethod method, {_proto}.MethodContext context)");
            StartBlock();
            AppendLine("try");
            StartBlock();
            AppendLine("await method.Invoke(context).ConfigureAwait(false);");
            EndBlock();
            AppendLine("catch (global::System.Exception ex)");
            StartBlock();
            AppendLine("HandleException(context, ex);");
            EndBlock();
            EndBlock();
            AppendLine("");

            AppendLine("// Override to customize exception handling for method invocations.");
            AppendLine($"protected virtual void HandleException({_proto}.MethodContext context, global::System.Exception ex)");
            StartBlock();
            AppendLine("if (context.HandleException(ex, shouldDisconnect: false))");
            StartBlock();
            AppendLine("return;");
            EndBlock();
            AppendLine($"if (ex is {_proto}.DBusErrorReplyException dbusEx)");
            StartBlock();
            AppendLine("context.ReplyError(dbusEx.ErrorName, dbusEx.ErrorMessage);");
            EndBlock();
            AppendLine("else if (ex is global::System.ArgumentException)");
            StartBlock();
            AppendLine("context.ReplyError(\"org.freedesktop.DBus.Error.InvalidArgs\", ex.Message);");
            EndBlock();
            AppendLine("else");
            StartBlock();
            AppendLine("context.ReplyError(\"org.freedesktop.DBus.Error.Failed\", ex.Message);");
            EndBlock();
            EndBlock();
            AppendLine("");

            AppendLine("// Override to filter interfaces for specific paths when the handler manages multiple paths.");
            AppendLine("protected virtual bool SupportsInterface(DBusInterface dbusInterface, global::System.ReadOnlySpan<char> path)");
            StartBlock();
            AppendLine("return true;");
            EndBlock();
            AppendLine("");

            // Add IntrospectAsync virtual method
            AppendLine("// Override to customize introspection, e.g. to include child node names.");
            AppendLine($"protected virtual {_vtask} HandleIntrospectAsync(IntrospectContext context)");
            StartBlock();
            AppendLine("DBusInterface interfaces = GetSupportedInterfaces(global::System.MemoryExtensions.AsSpan(context.MethodContext.Request.PathAsString));");
            AppendLine("context.Reply(interfaces);");
            AppendLine("return default;");
            EndBlock();
            AppendLine("");

            // Add IntrospectContext struct
            AppendLine("// Context for IntrospectAsync. Call Reply to send the introspection XML response.");
            AppendLine($"protected readonly struct IntrospectContext : {_idisposable}");
            StartBlock();
            AppendLine($"public {_proto}.MethodContext MethodContext {{ get; }}");
            AppendLine($"public IntrospectContext({_proto}.MethodContext methodContext)");
            StartBlock();
            AppendLine("MethodContext = methodContext;");
            EndBlock();
            AppendLine("public void Dispose() => MethodContext.Dispose();");
            AppendLine("public void Reply(DBusInterface interfaces, global::System.Collections.Generic.IList<string>? childNames = null)");
            StartBlock();

            // Create an array for interface XMLs (interfaces + 1 for potential DBusProperties)
            int interfaceCount = allInterfaces.Count + 1;
            AppendLine($"var interfaceXmls = new global::System.ReadOnlyMemory<byte>[{interfaceCount}];");
            AppendLine("int count = 0;");

            // Check each interface flag and add corresponding XML
            foreach (var interfaceName in allInterfaces)
            {
                string enumName = InterfaceNameToEnumValueName(interfaceName);
                AppendLine($"if ((interfaces & DBusInterface.{enumName}) != 0)");
                StartBlock();
                AppendLine($"interfaceXmls[count++] = {enumName}Xml;");
                EndBlock();
            }

            // Add DBusProperties if any interface has properties
            AppendLine("if ((interfaces & InterfacesWithProperties) != 0)");
            StartBlock();
            AppendLine($"interfaceXmls[count++] = {_proto}.IntrospectionXml.DBusProperties;");
            EndBlock();

            AppendLine("if (childNames is not null)");
            StartBlock();
            AppendLine("MethodContext.ReplyIntrospectXml(global::System.MemoryExtensions.AsSpan(interfaceXmls, 0, count), childNames);");
            EndBlock();
            AppendLine("else");
            StartBlock();
            AppendLine("MethodContext.ReplyIntrospectXml(global::System.MemoryExtensions.AsSpan(interfaceXmls, 0, count));");
            EndBlock();
            EndBlock();
            EndBlock();
            AppendLine("");

            // Generate DBusMethod struct inside DBusHandler
            AppendLine($"{(_anyHandlerPublic ? "protected internal" : "internal")} readonly struct DBusMethod");
            StartBlock();
            AppendLine($"private readonly {_func}<object, {_proto}.MethodContext, {_vtask}> _method;");
            AppendLine("private readonly object _target;");
            AppendLine("");
            AppendLine($"public DBusMethod({_func}<object, {_proto}.MethodContext, {_vtask}> method, object target)");
            StartBlock();
            AppendLine("_method = method;");
            AppendLine("_target = target;");
            EndBlock();
            AppendLine("");
            AppendLine("public bool HasValue => _method is not null;");
            AppendLine("");
            AppendLine($"public {_vtask} Invoke({_proto}.MethodContext context)");
            StartBlock();
            AppendLine("return _method?.Invoke(_target, context) ?? default;");
            EndBlock();
            EndBlock();
            AppendLine("");

            AppendLine($"{_vtask} {_proto}.IPathMethodHandler.HandleMethodAsync({_proto}.MethodContext context)");
            StartBlock();
            AppendLine("DBusInterface dbusInterface = ParseInterface(context);");
            AppendLine("DBusMethod method = (dbusInterface != OrgFreedesktopDBusIntrospectable && !SupportsInterface(dbusInterface, global::System.MemoryExtensions.AsSpan(context.Request.PathAsString))) ? default : FindMethodHandler(context, dbusInterface);");
            AppendLine("if (!method.HasValue)");
            StartBlock();
            AppendLine("return default;");
            EndBlock();
            AppendLine("return HandleAsync(method, context);");
            EndBlock();
            AppendLine("");
            AppendLine($"private {_vtask} HandleAsync(DBusMethod method, {_proto}.MethodContext context)");
            StartBlock();
            AppendLine($"{_syncCtx}? synchronizationContext = SynchronizationContext;");
            AppendLine("if (synchronizationContext is null)");
            StartBlock();
            AppendLine("return InvokeAsync(method, context);");
            EndBlock();
            AppendLine("else");
            StartBlock();
            AppendLine("context.DisposesAsynchronously = true;");
            AppendLine("synchronizationContext.Post(_postDelegate!, context);");
            AppendLine("return default;");
            EndBlock();
            EndBlock();
            AppendLine("");
            AppendLine($"private async {_vtask} InvokeAndDisposeAsync(DBusMethod method, {_proto}.MethodContext context)");
            StartBlock();
            AppendLine("try");
            StartBlock();
            AppendLine("await InvokeAsync(method, context).ConfigureAwait(false);");
            EndBlock();
            AppendLine("finally");
            StartBlock();
            AppendLine("context.Dispose();");
            EndBlock();
            EndBlock();
            AppendLine("");
            AppendLine($"private DBusMethod FindMethodHandler({_proto}.MethodContext context, DBusInterface dbusInterface)");
            StartBlock();
            AppendLine("return dbusInterface switch");
            StartBlock();
            foreach (var (ns, interfaceName, handlerInterfaceName) in _generatedHandlers)
            {
                string enumName = InterfaceNameToEnumValueName(interfaceName);
                // Skip IIntrospectable as it's now handled directly in DBusHandler
                if (handlerInterfaceName == "IIntrospectable")
                {
                    AppendLine($"{enumName} => FindIntrospectMethodHandler(this, context),");
                }
                else
                {
                    AppendLine($"DBusInterface.{enumName} when this is {ns}.{handlerInterfaceName} => {ns}.{handlerInterfaceName}.Helper.FindMethodHandler(this, context),");
                }
            }
            AppendLine("_ => default");
            _indentation--;
            AppendLine("};");
            EndBlock();
            AppendLine("");

            AppendLine($"private static DBusInterface ParseInterface({_proto}.MethodContext context)");
            StartBlock();
            AppendLine("string? dbusInterface = null;");
            AppendLine("if (context.IsPropertiesInterfaceRequest)");
            StartBlock();
            AppendLine("if (context.Request.Signature.Length > 0 && context.Request.Signature[0] == (byte)'s')");
            StartBlock();
            AppendLine("try");
            StartBlock();
            AppendLine($"{_proto}.Reader reader = context.Request.GetBodyReader();");
            AppendLine("dbusInterface = reader.ReadString();");
            EndBlock();
            AppendLine("catch { }");
            EndBlock();
            EndBlock();
            AppendLine("else");
            StartBlock();
            AppendLine("dbusInterface = context.Request.InterfaceAsString;");
            EndBlock();
            AppendLine("");
            AppendLine("var result = dbusInterface switch");
            StartBlock();
            // Add Introspectable interface as first item
            AppendLine("\"org.freedesktop.DBus.Introspectable\" => OrgFreedesktopDBusIntrospectable,");
            foreach (var interfaceName in allInterfaces)
            {
                string enumName = InterfaceNameToEnumValueName(interfaceName);
                AppendLine($"\"{interfaceName}\" => DBusInterface.{enumName},");
            }
            AppendLine("_ => default");
            _indentation--;
            AppendLine("};");
            AppendLine("return result;");
            EndBlock();
            AppendLine("");

            // Add FindIntrospectMethodHandler
            AppendLine($"private static DBusMethod FindIntrospectMethodHandler(object handler, {_proto}.MethodContext context)");
            StartBlock();
            AppendLine("var request = context.Request;");
            AppendLine("DBusMethod result = (request.MemberAsString, request.SignatureAsString) switch");
            StartBlock();
            AppendLine($"(\"Introspect\", \"\") => new DBusMethod(static (o, c) => (({handlerClassName})o).HandleIntrospectAsync(new IntrospectContext(c)), handler),");
            AppendLine("_ => default");
            _indentation--;
            AppendLine("};");
            AppendLine("return result;");
            EndBlock();
            AppendLine("");

            AppendLine("protected DBusInterface GetSupportedInterfaces(global::System.ReadOnlySpan<char> path)");
            StartBlock();
            AppendLine("DBusInterface interfaces = default;");

            // Add check for each generated interface
            foreach (var (ns, interfaceName, handlerInterfaceName) in _generatedHandlers)
            {
                // Skip IIntrospectable since it's handled separately
                if (handlerInterfaceName == "IIntrospectable")
                {
                    continue;
                }

                string enumName = InterfaceNameToEnumValueName(interfaceName);
                AppendLine($"if (SupportsInterface(DBusInterface.{enumName}, path) && this is {ns}.{handlerInterfaceName})");
                StartBlock();
                AppendLine($"interfaces |= DBusInterface.{enumName};");
                EndBlock();
            }

            AppendLine("return interfaces;");
            EndBlock();

            EndBlock();
            AppendLine("");

            EndBlock();

            return _sb.ToString();
        }

        private void AppendServiceClass(IEnumerable<InterfaceDescription> interfaceDescriptions, bool isPublic)
        {
            AppendLine($"{AccessModifier(isPublic)}static partial class ObjectFactory");
            StartBlock();
            foreach (var interf in interfaceDescriptions)
            {
                string interfaceName = interf.Name;
                AppendLine($"public static {interfaceName} Create{interfaceName}(this {_proto}.DBusService service, {_proto}.ObjectPath path) => new {interfaceName}(service.Connection, service.Name, path);");
            }
            EndBlock();
        }

        private void AppendReaderClass()
        {
            AppendLine("file static class MessageReader");
            StartBlock();

            foreach (var readMethod in _messageReadMethods)
            {
                AppendReadMessageMethod(readMethod.Key, readMethod.Value.Item1, readMethod.Value.Item2);
            }

            foreach (var readMethod in _typeReadMethods)
            {
                AppendReadTypeMethod(readMethod.Key, readMethod.Value);
            }

            EndBlock();
        }

        private void AppendMessageWriterExtensionsClass()
        {
            AppendLine("file static class MessageWriterExtensions");
            StartBlock();

            foreach (var writeMethod in _typeWriteMethods)
            {
                AppendWriteTypeMethod(writeMethod.Key, writeMethod.Value.Item1, writeMethod.Value.Item2);
            }

            EndBlock();
        }

        private void AppendReadTypeMethod(string method, string signature)
        {
            string dotnetReturnType = GetDotnetReadType(signature);
            AppendLine($"public static {dotnetReturnType} {method}(this ref {_proto}.Reader reader)");
            StartBlock();
            SignatureReader reader = new SignatureReader(Encoding.UTF8.GetBytes(signature));
            if (reader.TryRead(out DBusType type, out ReadOnlySpan<byte> innerSignature))
            {
                reader = new SignatureReader(innerSignature);
                if (type == DBusType.Array)
                {
                    if (!reader.TryRead(out DBusType itemType, out ReadOnlySpan<byte> itemInnerSignature))
                    {
                        ThrowInvalidSignature(signature);
                    }
                    if (itemType == DBusType.DictEntry)
                    {
                        reader = new SignatureReader(itemInnerSignature);
                        if (!reader.TryRead(out DBusType keyType, out ReadOnlySpan<byte> keyInnerSignature))
                        {
                            ThrowInvalidSignature(signature);
                        }
                        if (!reader.TryRead(out DBusType valueType, out ReadOnlySpan<byte> valueInnerSignature))
                        {
                            ThrowInvalidSignature(signature);
                        }

                        string dotnetKeyType = GetDotnetReadType(keyType, keyInnerSignature);
                        string dotnetValueType = GetDotnetReadType(valueType, valueInnerSignature);
                        string keyTypeSignature = GetSignature(keyType, keyInnerSignature);
                        string valueTypeSignature = GetSignature(valueType, valueInnerSignature);

                        AppendLine($"global::System.Collections.Generic.Dictionary<{dotnetKeyType}, {dotnetValueType}> dictionary = new();");
                        AppendLine($"{_proto}.ArrayEnd dictEnd = reader.ReadDictionaryStart();");

                        AppendLine($"while (reader.HasNext(dictEnd))");
                        StartBlock();
                        AppendLine($"var key = {CallReadArgumentType(keyTypeSignature)};");
                        AppendLine($"var value = {CallReadArgumentType(valueTypeSignature)};");
                        AppendLine($"dictionary[key] = value;");
                        EndBlock();

                        AppendLine($"return dictionary;");
                    }
                    else
                    {
                        string dotnetItemType = GetDotnetReadType(itemType, itemInnerSignature);

                        AppendLine($"global::System.Collections.Generic.List<{dotnetItemType}> list = new();");
                        AppendLine($"{_proto}.ArrayEnd arrayEnd = reader.ReadArrayStart({GetDBusTypeEnumValue(itemType)});");

                        AppendLine($"while (reader.HasNext(arrayEnd))");
                        StartBlock();
                        AppendLine($"list.Add({CallReadArgumentType(Encoding.UTF8.GetString(innerSignature))});");
                        EndBlock();

                        AppendLine($"return list.ToArray();");
                    }
                }
                else if (type == DBusType.Struct)
                {
                    AppendLine("reader.AlignStruct();");
                    List<string> fields = new();
                    while (reader.TryRead(out DBusType fieldType, out ReadOnlySpan<byte> fieldInnerSignature))
                    {
                        fields.Add(CallReadArgumentType(GetSignature(fieldType, fieldInnerSignature)));
                    }
                    if (fields.Count == 1)
                    {
                        AppendLine($"return new {GetDotnetReadType(signature)}({string.Join(", ", fields)});");
                    }
                    else
                    {
                        AppendLine($"return ({string.Join(", ", fields)});");
                    }
                }
                else
                {
                    ThrowInvalidSignature(signature);
                }
            }
            EndBlock();
        }

        private void AppendWriteTypeMethod(string method, bool variant, string signature)
        {
            string dotnetArgType = GetDotnetWriteType(signature);
            AppendLine($"public static void {method}(this ref {_proto}.MessageWriter writer, {dotnetArgType} value)");
            StartBlock();
            if (variant)
            {
                AppendLine($"writer.WriteSignature(\"{signature}\");");
                AppendLine($"{CallWriteArgumentType(signature, "value")};");
            }
            else
            {
                SignatureReader reader = new SignatureReader(Encoding.UTF8.GetBytes(signature));
                if (reader.TryRead(out DBusType type, out ReadOnlySpan<byte> innerSignature))
                {
                    reader = new SignatureReader(innerSignature);
                    if (type == DBusType.Array)
                    {
                        if (!reader.TryRead(out DBusType itemType, out ReadOnlySpan<byte> itemInnerSignature))
                        {
                            ThrowInvalidSignature(signature);
                        }
                        if (itemType == DBusType.DictEntry)
                        {
                            reader = new SignatureReader(itemInnerSignature);
                            if (!reader.TryRead(out DBusType keyType, out ReadOnlySpan<byte> keyInnerSignature))
                            {
                                ThrowInvalidSignature(signature);
                            }
                            if (!reader.TryRead(out DBusType valueType, out ReadOnlySpan<byte> valueInnerSignature))
                            {
                                ThrowInvalidSignature(signature);
                            }

                            string keyTypeSignature = GetSignature(keyType, keyInnerSignature);
                            string valueTypeSignature = GetSignature(valueType, valueInnerSignature);

                            AppendLine($"{_proto}.ArrayStart arrayStart = writer.WriteDictionaryStart();");
                            AppendLine($"foreach (var item in value)");
                            StartBlock();
                            AppendLine($"writer.WriteDictionaryEntryStart();");
                            AppendLine($"{CallWriteArgumentType(keyTypeSignature, "item.Key")};");
                            AppendLine($"{CallWriteArgumentType(valueTypeSignature, "item.Value")};");
                            EndBlock();
                            AppendLine($"writer.WriteDictionaryEnd(arrayStart);");
                        }
                        else
                        {
                            string dotnetItemSignature = GetSignature(itemType, itemInnerSignature);

                            AppendLine($"{_proto}.ArrayStart arrayStart = writer.WriteArrayStart({GetDBusTypeEnumValue(itemType)});");
                            AppendLine($"foreach (var item in value)");
                            StartBlock();
                            AppendLine($"{CallWriteArgumentType(dotnetItemSignature, "item")};");
                            EndBlock();
                            AppendLine($"writer.WriteArrayEnd(arrayStart);");
                        }
                    }
                    else if (type == DBusType.Struct)
                    {
                        AppendLine($"writer.WriteStructureStart();");
                        int i = 1;
                        while (reader.TryRead(out DBusType fieldType, out ReadOnlySpan<byte> fieldInnerSignature))
                        {
                            string fieldSignature = GetSignature(fieldType, fieldInnerSignature);
                            string parameterName = i < 8 ? $"value.Item{i}" : $"value.Rest.Item{1 + (i % 8)}";
                            AppendLine($"{CallWriteArgumentType(fieldSignature, parameterName)};");
                            i++;
                        }
                    }
                    else
                    {
                        ThrowInvalidSignature(signature);
                    }
                }
            }
            EndBlock();
        }

        private void AppendHandlerTypesForInterface(string ns, string name, string handlerName, XElement interfaceXml, bool isPublic)
        {
            string interfaceName = (string)interfaceXml.Attribute("name");

            var readableProperties = ReadableProperties(interfaceXml).Select(ToArgument).ToArray();
            var readWriteProperties = ReadWriteProperties(interfaceXml).Select(ToArgument).ToArray();
            var writeOnlyProperties = WriteOnlyProperties(interfaceXml).Select(ToArgument).ToArray();
            var writableProperties = WritableProperties(interfaceXml).Select(ToArgument).ToArray();

            AppendLine($"{AccessModifier(isPublic)}interface I{handlerName}");
            StartBlock();

            // Track this handler for the shared FindMethodHandler implementation
            _generatedHandlers.Add((ns, interfaceName, $"I{handlerName}"));

            // Always add Helper class for all handler interfaces
            AppendLine("internal static class Helper");
            StartBlock();

            if (readableProperties.Any() || writableProperties.Any())
            {
                // Single method that returns int for all properties
                AppendLine("public static int GetPropertyValue(string propertyName)");
                StartBlock();
                AppendLine("return propertyName switch");
                StartBlock();

                // Add readable properties with their index values
                for (int i = 0; i < readableProperties.Length; i++)
                {
                    var property = readableProperties[i];
                    AppendLine($"\"{property.Name}\" => {i + 1},");
                }

                // Add write-only properties with their values
                int nextValue = readableProperties.Length + 1;
                for (int i = 0; i < writeOnlyProperties.Length; i++)
                {
                    var property = writeOnlyProperties[i];
                    AppendLine($"\"{property.Name}\" => {nextValue + i},");
                }

                AppendLine("_ => 0");
                _indentation--;
                AppendLine("};");
                EndBlock();
            }

            // Add FindMethodHandler method to Helper class
            AppendLine($"public static {HandlerTypeRef}.DBusMethod FindMethodHandler(object handler, {_proto}.MethodContext context)");
            StartBlock();
            AppendLine("var request = context.Request;");

            // Handle property methods separately
            if (readableProperties.Any() || writableProperties.Any())
            {
                AppendLine("if (context.IsPropertiesInterfaceRequest)");
                StartBlock();
                AppendLine("return (request.MemberAsString, request.SignatureAsString) switch");
                StartBlock();

                if (readableProperties.Any())
                {
                    AppendLine($"(\"Get\", \"ss\") => new {HandlerTypeRef}.DBusMethod(static (o, c) => ((I{handlerName})o).HandleGetPropertyAsync(new GetPropertyContext(c)), handler),");
                    AppendLine($"(\"GetAll\", \"s\") => new {HandlerTypeRef}.DBusMethod(static (o, c) => ((I{handlerName})o).HandleGetAllPropertiesAsync(new GetAllPropertiesContext(c)), handler),");
                }

                if (writableProperties.Any())
                {
                    AppendLine($"(\"Set\", \"ssv\") => new {HandlerTypeRef}.DBusMethod(static (o, c) => ((I{handlerName})o).HandleSetPropertyAsync(new SetPropertyContext(c)), handler),");
                }

                AppendLine("_ => default");
                _indentation--;
                AppendLine("};");
                EndBlock();
            }

            // Handle regular interface methods
            var methods = interfaceXml.Elements("method").ToArray();
            if (methods.Any())
            {
                AppendLine("return (request.MemberAsString, request.SignatureAsString) switch");
                StartBlock();

                foreach (var method in methods)
                {
                    string dbusMethodName = (string)method.Attribute("name");
                    string dotnetMethodName = Prettify(dbusMethodName);
                    var inArgs = method.Elements("arg").Where(arg => (arg.Attribute("direction")?.Value ?? "in") == "in").Select(ToArgument).ToArray();
                    string signature = string.Join("", inArgs.Select(a => a.Signature));

                    AppendLine($"(\"{dbusMethodName}\", \"{signature}\") => new {HandlerTypeRef}.DBusMethod(static (o, c) => Handle{dotnetMethodName}Async((I{handlerName})o, c), handler),");
                }

                AppendLine("_ => default");
                _indentation--;
                AppendLine("};");
            }
            else
            {
                // No methods, just return default
                AppendLine("return default;");
            }

            EndBlock();

            // Generate static Handle methods that read args, call the interface method, and send the reply
            foreach (var method in methods)
            {
                string dbusMethodName = (string)method.Attribute("name");
                string dotnetMethodName = Prettify(dbusMethodName);
                var inArgs = method.Elements("arg").Where(arg => (arg.Attribute("direction")?.Value ?? "in") == "in").Select(ToArgument).ToArray();
                var outArgs = method.Elements("arg").Where(arg => arg.Attribute("direction")?.Value == "out").Select(ToArgument).ToArray();

                AppendLine($"static async {_vtask} Handle{dotnetMethodName}Async(I{handlerName} handler, {_proto}.MethodContext context)");
                StartBlock();

                // Read args
                if (inArgs.Length > 0)
                {
                    string readMessageName = GetReadMessageMethodName(inArgs, variant: false);
                    if (inArgs.Length == 1)
                    {
                        AppendLine($"var {inArgs[0].NameLower} = MessageReader.{readMessageName}(context.Request);");
                    }
                    else
                    {
                        string destructure = string.Join(", ", inArgs.Select(a => a.NameLower));
                        AppendLine($"var ({destructure}) = MessageReader.{readMessageName}(context.Request);");
                    }
                }

                // Call handler method
                string callArgs = string.Join(", ", inArgs.Select(a => a.NameLower));
                if (outArgs.Length == 1)
                {
                    string outSignature = string.Join("", outArgs.Select(a => a.Signature));
                    string resultType = outArgs[0].DotnetReadType;
                    AppendLine($"var result = await handler.{dotnetMethodName}Async({callArgs}).ConfigureAwait(false);");
                    AppendLine("WriteReply(context, result);");
                    AppendLine($"static void WriteReply({_proto}.MethodContext context, {resultType} result)");
                    StartBlock();
                    AppendLine($"var writer = context.CreateReplyWriter(\"{outSignature}\");");
                    AppendLine($"{CallWriteArgumentType(outArgs[0].Signature, "result")};");
                    AppendLine("context.Reply(writer.CreateMessage());");
                    EndBlock();
                }
                else if (outArgs.Length > 1)
                {
                    string outSignature = string.Join("", outArgs.Select(a => a.Signature));
                    string tupleType = TupleOf(outArgs.Select(a => $"{a.DotnetReadType} {a.NameUpper}"));
                    AppendLine($"var result = await handler.{dotnetMethodName}Async({callArgs}).ConfigureAwait(false);");
                    AppendLine("WriteReply(context, result);");
                    AppendLine($"static void WriteReply({_proto}.MethodContext context, {tupleType} result)");
                    StartBlock();
                    AppendLine($"var writer = context.CreateReplyWriter(\"{outSignature}\");");
                    foreach (var outArg in outArgs)
                    {
                        AppendLine($"{CallWriteArgumentType(outArg.Signature, $"result.{outArg.NameUpper}")};");
                    }
                    AppendLine("context.Reply(writer.CreateMessage());");
                    EndBlock();
                }
                else
                {
                    AppendLine($"await handler.{dotnetMethodName}Async({callArgs}).ConfigureAwait(false);");
                    AppendLine("context.Reply(context.CreateReplyWriter(null).CreateMessage());");
                }

                EndBlock();
            }

            EndBlock(); // End Helper class

            if (readableProperties.Any())
            {
                AppendLine($"{_vtask} HandleGetPropertyAsync(GetPropertyContext context);");

                AppendLine($"{_vtask} HandleGetAllPropertiesAsync(GetAllPropertiesContext context);");
            }

            if (writableProperties.Any())
            {
                AppendLine($"{_vtask} HandleSetPropertyAsync(SetPropertyContext context);");
            }

            foreach (var method in interfaceXml.Elements("method"))
            {
                string dbusMethodName = (string)method.Attribute("name");
                string dotnetMethodName = Prettify(dbusMethodName);
                var inArgs = method.Elements("arg").Where(arg => (arg.Attribute("direction")?.Value ?? "in") == "in").Select(ToArgument).ToArray();
                var outArgs = method.Elements("arg").Where(arg => arg.Attribute("direction")?.Value == "out").Select(ToArgument).ToArray();

                string parameters = string.Join(", ", inArgs.Select(a => $"{a.DotnetReadType} {a.NameLower}"));
                string returnType;
                if (outArgs.Length == 0)
                {
                    returnType = _vtask;
                }
                else if (outArgs.Length == 1)
                {
                    returnType = $"{_vtask}<{outArgs[0].DotnetReadType}>";
                }
                else
                {
                    string tupleType = TupleOf(outArgs.Select(a => $"{a.DotnetReadType} {a.NameUpper}"));
                    returnType = $"{_vtask}<{tupleType}>";
                }
                AppendLine($"{returnType} {dotnetMethodName}Async({parameters});");
            }

            if (readableProperties.Any())
            {
                // Generate GetPropertyContext
                string propertyEnumName = $"{name}Property";
                AppendLine($"readonly struct GetPropertyContext : {_idisposable}");
                StartBlock();

                AppendLine($"public {_proto}.MethodContext MethodContext {{ get; }}");
                AppendLine($"public {propertyEnumName} Property {{ get; }}");
                AppendLine($"public GetPropertyContext({_proto}.MethodContext methodContext)");
                StartBlock();
                AppendLine("MethodContext = methodContext;");
                AppendLine("var reader = methodContext.Request.GetBodyReader();");
                AppendLine("reader.ReadStringAsSpan(); // Skip interface name");
                AppendLine($"Property = ({propertyEnumName})Helper.GetPropertyValue(reader.ReadString());");
                EndBlock();

                AppendLine("public void Dispose() => MethodContext.Dispose();");

                // Add strongly typed Reply methods for each readable property
                foreach (var property in readableProperties)
                {
                    string writeMethodName = GetWriteTypeMethodName(property.Signature, variant: true);
                    AppendLine($"public void Reply{property.NameUpper}({property.DotnetReadType} value)");
                    StartBlock();
                    AppendLine($"global::System.Diagnostics.Debug.Assert(Property == {propertyEnumName}.{property.NameUpper});");
                    AppendLine("var writer = MethodContext.CreateReplyWriter(\"v\");");
                    AppendLine($"writer.{writeMethodName}(value);");
                    AppendLine("MethodContext.Reply(writer.CreateMessage());");
                    EndBlock();
                }

                // Add ReplyErrorUnknownProperty method
                AppendLine("public void ReplyErrorUnknownProperty()");
                StartBlock();
                AppendLine("MethodContext.ReplyError(\"org.freedesktop.DBus.Error.UnknownProperty\", $\"Unknown property: {Property}\");");
                EndBlock();

                AppendLine($"public {_vtask} Handle(I{name}Properties properties)");
                StartBlock();
                AppendLine("switch (Property)");
                StartBlock();
                foreach (var property in readableProperties)
                {
                    AppendLine($"case {propertyEnumName}.{property.NameUpper}:");
                    _indentation++;
                    AppendLine($"Reply{property.NameUpper}(properties.{property.NameUpper});");
                    AppendLine("break;");
                    _indentation--;
                }
                AppendLine("default:");
                _indentation++;
                AppendLine("ReplyErrorUnknownProperty();");
                AppendLine("break;");
                _indentation--;
                EndBlock();
                AppendLine("return default;");
                EndBlock();

                EndBlock();

                // Generate GetAllPropertiesContext
                AppendLine($"readonly struct GetAllPropertiesContext : {_idisposable}");
                StartBlock();

                AppendLine($"public {_proto}.MethodContext MethodContext {{ get; }}");
                AppendLine($"public GetAllPropertiesContext({_proto}.MethodContext methodContext)");
                StartBlock();
                AppendLine("MethodContext = methodContext;");
                EndBlock();

                AppendLine("public void Dispose() => MethodContext.Dispose();");

                AppendLine($"public {_vtask} Handle(I{name}Properties properties)");
                StartBlock();
                AppendLine("var writer = MethodContext.CreateReplyWriter(\"a{sv}\");");
                AppendLine("var dictStart = writer.WriteDictionaryStart();");
                foreach (var property in readableProperties)
                {
                    string writeMethodName = GetWriteTypeMethodName(property.Signature, variant: true);
                    AppendLine($"writer.WriteDictionaryEntryStart();");
                    AppendLine($"writer.WriteString(\"{property.Name}\");");
                    AppendLine($"writer.{writeMethodName}(properties.{property.NameUpper});");
                }
                AppendLine("writer.WriteDictionaryEnd(dictStart);");
                AppendLine("MethodContext.Reply(writer.CreateMessage());");
                AppendLine("return default;");
                EndBlock();

                // Handle overload that accepts all gettable properties as nullable individual arguments (alphabetically sorted)
                var sortedReadableProperties = readableProperties.OrderBy(p => p.NameUpper).ToArray();
                string handleArgs = string.Join(", ", sortedReadableProperties.Select(p => $"{GetNullableType(p.DotnetWriteType)} {p.NameLower} = default"));
                AppendLine($"public {_vtask} Handle({handleArgs})");
                StartBlock();
                AppendLine("var writer = MethodContext.CreateReplyWriter(\"a{sv}\");");
                AppendLine("var dictStart = writer.WriteDictionaryStart();");
                foreach (var property in readableProperties)
                {
                    var sortedProp = sortedReadableProperties.First(p => p.Name == property.Name);
                    string writeMethodName = GetWriteTypeMethodName(property.Signature, variant: true);
                    AppendLine($"if ({sortedProp.NameLower} is not null)");
                    StartBlock();
                    AppendLine($"writer.WriteDictionaryEntryStart();");
                    AppendLine($"writer.WriteString(\"{property.Name}\");");
                    AppendLine($"writer.{writeMethodName}(({property.DotnetWriteType}){sortedProp.NameLower});");
                    EndBlock();
                }
                AppendLine("writer.WriteDictionaryEnd(dictStart);");
                AppendLine("MethodContext.Reply(writer.CreateMessage());");
                AppendLine("return default;");
                EndBlock();

                EndBlock();
            }

            if (writableProperties.Any())
            {
                // Generate SetPropertyContext
                string writablePropertyEnumName = $"Writable{name}Property";
                AppendLine($"readonly struct SetPropertyContext : {_idisposable}");
                StartBlock();

                AppendLine($"public {_proto}.MethodContext MethodContext {{ get; }}");
                AppendLine($"public {writablePropertyEnumName} Property {{ get; }}");
                AppendLine($"public SetPropertyContext({_proto}.MethodContext methodContext)");
                StartBlock();
                AppendLine("MethodContext = methodContext;");
                AppendLine("var reader = methodContext.Request.GetBodyReader();");
                AppendLine("reader.ReadStringAsSpan(); // Skip interface name");
                AppendLine($"Property = ({writablePropertyEnumName})Helper.GetPropertyValue(reader.ReadString());");
                EndBlock();

                AppendLine("public void Dispose() => MethodContext.Dispose();");

                // Add Read{PropertyName} methods for each writable property
                foreach (var property in writableProperties)
                {
                    string readMethodName = GetReadMessageMethodName(new[] { property }, variant: true);
                    AppendLine($"public {property.DotnetReadType} Read{property.NameUpper}()");
                    StartBlock();
                    AppendLine("var reader = MethodContext.Request.GetBodyReader();");
                    AppendLine("reader.ReadStringAsSpan(); // Skip interface name");
                    AppendLine("reader.ReadStringAsSpan(); // Skip property name");
                    AppendLine($"reader.ReadSignature(\"{property.Signature}\"u8);");
                    AppendLine($"return {CallReadArgumentType(property.Signature)};");
                    EndBlock();
                }

                // Reply method - acknowledges the set
                AppendLine("public void Reply()");
                StartBlock();
                AppendLine("MethodContext.Reply(MethodContext.CreateReplyWriter(null).CreateMessage());");
                EndBlock();

                // Add ReplyErrorUnknownProperty method
                AppendLine("public void ReplyErrorUnknownProperty()");
                StartBlock();
                AppendLine("MethodContext.ReplyError(\"org.freedesktop.DBus.Error.UnknownProperty\", $\"Unknown property: {Property}\");");
                EndBlock();

                // Add ReplyErrorReadOnlyProperty method
                AppendLine("public void ReplyErrorReadOnlyProperty()");
                StartBlock();
                AppendLine("MethodContext.ReplyError(\"org.freedesktop.DBus.Error.PropertyReadOnly\", $\"Property is read-only: {Property}\");");
                EndBlock();

                // Handle method that sets on IXxxProperties
                AppendLine($"public {_vtask} Handle(I{name}Properties properties)");
                StartBlock();
                AppendLine("switch (Property)");
                StartBlock();
                foreach (var property in writableProperties)
                {
                    AppendLine($"case {writablePropertyEnumName}.{property.NameUpper}:");
                    _indentation++;
                    AppendLine($"properties.{property.NameUpper} = Read{property.NameUpper}();");
                    AppendLine("Reply();");
                    AppendLine("break;");
                    _indentation--;
                }
                AppendLine($"case {writablePropertyEnumName}.UnknownProperty:");
                _indentation++;
                AppendLine("ReplyErrorUnknownProperty();");
                AppendLine("break;");
                _indentation--;
                AppendLine("default:");
                _indentation++;
                AppendLine("ReplyErrorReadOnlyProperty();");
                AppendLine("break;");
                _indentation--;
                EndBlock();
                AppendLine("return default;");
                EndBlock();

                EndBlock();
            }

            EndBlock();
        }

        private void AppendPropertyTypes(string name, XElement interfaceXml, bool generateProxies, bool generateHandlers, bool isProxyPublic, bool isHandlerPublic)
        {
            string interfaceName = (string)interfaceXml.Attribute("name");

            var readableProperties = ReadableProperties(interfaceXml).Select(ToArgument).ToArray();
            var readWriteProperties = ReadWriteProperties(interfaceXml).Select(ToArgument).ToArray();
            var writeOnlyProperties = WriteOnlyProperties(interfaceXml).Select(ToArgument).ToArray();
            var writableProperties = WritableProperties(interfaceXml).Select(ToArgument).ToArray();

            if (generateHandlers)
            {
                _allInterfaces.Add(interfaceName);
                _interfaceXmls[interfaceName] = interfaceXml;

                if (readableProperties.Any() || writableProperties.Any())
                {
                    _interfacesWithProperties.Add(interfaceName);
                }
            }

            if (readableProperties.Any())
            {
                AppendPropertyEnum(name, readableProperties, isProxyPublic || isHandlerPublic);
            }

            if (readableProperties.Any() || writableProperties.Any())
            {
                AppendLine($"{AccessModifier(isProxyPublic || isHandlerPublic)}interface I{name}Properties");
                StartBlock();
                foreach (var property in readableProperties)
                {
                    bool isWritable = writableProperties.Any(w => w.Name == property.Name);
                    if (isWritable)
                    {
                        AppendLine($"{property.DotnetReadType} {property.NameUpper} {{ get; set; }}");
                    }
                    else
                    {
                        AppendLine($"{property.DotnetReadType} {property.NameUpper} {{ get; }}");
                    }
                }
                foreach (var property in writeOnlyProperties)
                {
                    AppendLine($"{property.DotnetReadType} {property.NameUpper} {{ set; }}");
                }
                EndBlock();
            }

            if (generateHandlers)
            {
                // WritableProperty enum
                if (writableProperties.Any())
                {
                    string writablePropertyEnumName = $"Writable{name}Property";
                    AppendLine($"{AccessModifier(isHandlerPublic)}enum {writablePropertyEnumName}");
                    StartBlock();
                    AppendLine("UnknownProperty = 0,");

                    foreach (var property in readWriteProperties)
                    {
                        int index = Array.FindIndex(readableProperties, p => p.Name == property.Name);
                        if (index >= 0)
                        {
                            AppendLine($"{property.NameUpper} = {index + 1},");
                        }
                    }

                    int nextValue = readableProperties.Length + 1;
                    for (int i = 0; i < writeOnlyProperties.Length; i++)
                    {
                        var property = writeOnlyProperties[i];
                        string comma = i < writeOnlyProperties.Length - 1 ? "," : "";
                        AppendLine($"{property.NameUpper} = {nextValue + i}{comma}");
                    }
                    EndBlock();
                }
            }

            if (generateProxies)
            {
                if (readableProperties.Any())
                {
                    string propertiesClassName = $"{name}Properties";
                    string propertyEnumName = $"{name}Property";
                    string nullableInterfaceName = $"INullable{propertiesClassName}";
                    string changedInterfaceName = $"IChanged{propertiesClassName}";

                    bool useByteArray = readableProperties.Length > 64;

                    AppendLine($"{AccessModifier(isProxyPublic)}interface {nullableInterfaceName}");
                    StartBlock();
                    foreach (var property in readableProperties)
                    {
                        AppendLine($"{GetNullableType(property.DotnetReadType)} {property.NameUpper} {{ get; }}");
                    }
                    AppendLine("bool AreAllPropertiesSet();");
                    AppendLine($"{propertiesClassName} EnsureAllPropertiesSet();");
                    EndBlock();

                    AppendLine($"{AccessModifier(isProxyPublic)}interface {changedInterfaceName} : {nullableInterfaceName}");
                    StartBlock();
                    foreach (var property in readableProperties)
                    {
                        AppendLine($"bool Has{property.NameUpper}Changed {{ get; }}");
                    }
                    EndBlock();

                    AppendLine($"{AccessModifier(isProxyPublic)}sealed class {propertiesClassName} : {changedInterfaceName}, I{name}Properties");
                    StartBlock();

                    if (useByteArray)
                    {
                        int byteCount = (readableProperties.Length + 7) / 8;
                        var allSetBytes = new byte[byteCount];
                        for (int i = 0; i < byteCount - 1; i++)
                            allSetBytes[i] = 0xFF;
                        int remainder = readableProperties.Length % 8;
                        allSetBytes[byteCount - 1] = remainder == 0 ? (byte)0xFF : (byte)((1 << remainder) - 1);
                        string allSetLiteral = string.Join(", ", allSetBytes.Select(b => $"0x{b:X2}"));

                        AppendLine($"private byte[] __set = new byte[{byteCount}];");
                        AppendLine($"private byte[] __invalidated = new byte[{byteCount}];");
                        AppendLine($"private static global::System.ReadOnlySpan<byte> PropertiesAllSet => new byte[] {{ {allSetLiteral} }}; // {readableProperties.Length} properties");
                        AppendLine($"private static int FlagIndex({propertyEnumName} property) => ((int)property - 1) / 8;");
                        AppendLine($"private static byte FlagMask({propertyEnumName} property) => (byte)(1 << (((int)property - 1) % 8));");
                    }
                    else
                    {
                        string flagType = readableProperties.Length <= 32 ? "uint" : "ulong";
                        string one = readableProperties.Length <= 32 ? "1U" : "1UL";

                        string allSetValue;
                        if (readableProperties.Length <= 32)
                        {
                            uint value = readableProperties.Length == 32 ? uint.MaxValue : (1U << readableProperties.Length) - 1;
                            allSetValue = $"0x{value:X}U";
                        }
                        else
                        {
                            ulong value = readableProperties.Length == 64 ? ulong.MaxValue : (1UL << readableProperties.Length) - 1;
                            allSetValue = $"0x{value:X}UL";
                        }

                        AppendLine($"private {flagType} __set;");
                        AppendLine($"private {flagType} __invalidated;");
                        AppendLine($"private const {flagType} PropertiesAllSet = {allSetValue}; // {readableProperties.Length} properties");

                        AppendLine($"private static {flagType} Flag({propertyEnumName} property) => property == 0 ? 0 : {one} << ((int)property - 1);");
                    }

                    AppendLine($"public {propertiesClassName}() {{ }}");
                    AppendLine("#nullable disable");
                    AppendLine("[global::System.Diagnostics.CodeAnalysis.SetsRequiredMembers]");
                    AppendLine($"private {propertiesClassName}(bool _) {{ }}");
                    AppendLine("#nullable enable");

                    AppendLine($"private void EnsureSet({propertyEnumName} property)");
                    StartBlock();
                    AppendLine("if (!HasFlag(__set, property))");
                    StartBlock();
                    AppendLine("throw new global::System.InvalidOperationException(\"Property is not set.\");");
                    EndBlock();
                    EndBlock();

                    foreach (var property in readableProperties)
                    {
                        AppendLine($"private {property.DotnetReadType} {property.UnderscoreNameLower} = default!;");
                        AppendLine($"public required {property.DotnetReadType} {property.NameUpper}");
                        StartBlock();
                        AppendLine($"get {{ EnsureSet({propertyEnumName}.{property.NameUpper}); return {property.UnderscoreNameLower}; }}");
                        if (useByteArray)
                        {
                            AppendLine($"set {{ {property.UnderscoreNameLower} = value; __set[FlagIndex({propertyEnumName}.{property.NameUpper})] |= FlagMask({propertyEnumName}.{property.NameUpper}); }}");
                        }
                        else
                        {
                            AppendLine($"set {{ {property.UnderscoreNameLower} = value; __set |= Flag({propertyEnumName}.{property.NameUpper}); }}");
                        }
                        EndBlock();
                    }

                    foreach (var property in readableProperties)
                    {
                        string nullableType = GetNullableType(property.DotnetReadType);
                        AppendLine($"{nullableType} {nullableInterfaceName}.{property.NameUpper}");
                        _indentation++;
                        AppendLine($"=> IsSet({propertyEnumName}.{property.NameUpper}) ? {property.UnderscoreNameLower} : default({nullableType});");
                        _indentation--;
                    }

                    foreach (var property in readableProperties)
                    {
                        AppendLine($"bool {changedInterfaceName}.Has{property.NameUpper}Changed");
                        _indentation++;
                        AppendLine($"=> IsSet({propertyEnumName}.{property.NameUpper}) || IsInvalidated({propertyEnumName}.{property.NameUpper});");
                        _indentation--;
                    }

                    AppendLine($"{propertiesClassName} {nullableInterfaceName}.EnsureAllPropertiesSet()");
                    StartBlock();
                    AppendLine("EnsureAllPropertiesSet();");
                    AppendLine("return this;");
                    EndBlock();

                    AppendLine($"public static {propertiesClassName} CreateUninitialized() => new {propertiesClassName}(false);");

                    if (useByteArray)
                    {
                        AppendLine($"private bool HasFlag(byte[] flags, {propertyEnumName} property)");
                        _indentation++;
                        AppendLine($"=> property != 0 && (flags[FlagIndex(property)] & FlagMask(property)) != 0;");
                        _indentation--;
                    }
                    else
                    {
                        string flagType = readableProperties.Length <= 32 ? "uint" : "ulong";
                        AppendLine($"private bool HasFlag({flagType} flags, {propertyEnumName} property)");
                        _indentation++;
                        AppendLine($"=> property != 0 && (flags & Flag(property)) != 0;");
                        _indentation--;
                    }

                    AppendLine($"public bool IsSet({propertyEnumName} property) => HasFlag(__set, property);");
                    AppendLine($"public bool IsInvalidated({propertyEnumName} property) => HasFlag(__invalidated, property);");

                    AppendLine($"public void SetInvalidated({propertyEnumName} property)");
                    StartBlock();
                    AppendLine("if (property != 0)");
                    StartBlock();
                    if (useByteArray)
                    {
                        AppendLine("__invalidated[FlagIndex(property)] |= FlagMask(property);");
                    }
                    else
                    {
                        AppendLine("__invalidated |= Flag(property);");
                    }
                    EndBlock();
                    EndBlock();

                    if (useByteArray)
                    {
                        AppendLine($"public bool AreAllPropertiesSet() => global::System.MemoryExtensions.SequenceEqual(PropertiesAllSet, __set);");
                    }
                    else
                    {
                        AppendLine($"public bool AreAllPropertiesSet() => __set == PropertiesAllSet;");
                    }

                    AppendLine("public void EnsureAllPropertiesSet()");
                    StartBlock();
                    AppendLine("if (!AreAllPropertiesSet())");
                    StartBlock();
                    if (useByteArray)
                    {
                        AppendLine($"throw new {_proto}.DBusUnexpectedValueException(\"Not all properties have been set (\" + global::System.BitConverter.ToString(__set) + \").\");");
                    }
                    else
                    {
                        AppendLine($"throw new {_proto}.DBusUnexpectedValueException($\"Not all properties have been set (0x{{__set:x}}).\");");
                    }
                    EndBlock();
                    EndBlock();

                    AppendLine($"public static {propertiesClassName} ReadFrom(ref {_proto}.Reader reader, bool withInvalidated)");
                    StartBlock();
                    AppendLine($"var props = CreateUninitialized();");
                    AppendLine($"{_proto}.ArrayEnd arrayEnd = reader.ReadArrayStart({GetDBusTypeEnumValue(DBusType.Struct)});");
                    AppendLine("while (reader.HasNext(arrayEnd))");
                    StartBlock();

                    AppendLine("var property = reader.ReadString();");
                    AppendLine("switch (property)");
                    StartBlock();

                    foreach (var property in readableProperties)
                    {
                        AppendLine($"case \"{property.Name}\":");
                        _indentation++;
                        AppendLine($"reader.ReadSignature(\"{property.Signature}\"u8);");
                        AppendLine($"props.{property.NameUpper} = {CallReadArgumentType(property.Signature)};");
                        AppendLine("break;");
                        _indentation--;
                    }
                    AppendLine("default:");
                    _indentation++;
                    AppendLine($"reader.ReadVariantValue();");
                    AppendLine("break;");
                    _indentation--;

                    EndBlock(); // switch

                    EndBlock(); // while

                    AppendLine("if (withInvalidated)");
                    StartBlock();
                    AppendLine($"{_proto}.ArrayEnd invalidatedEnd = reader.ReadArrayStart({GetDBusTypeEnumValue(DBusType.String)});");
                    AppendLine("while (reader.HasNext(invalidatedEnd))");
                    StartBlock();
                    AppendLine("var propertyName = reader.ReadString();");
                    if (useByteArray)
                    {
                        AppendLine("switch (propertyName)");
                        StartBlock();
                        foreach (var property in readableProperties)
                        {
                            AppendLine($"case \"{property.Name}\":");
                            _indentation++;
                            AppendLine($"props.__invalidated[FlagIndex({propertyEnumName}.{property.NameUpper})] |= FlagMask({propertyEnumName}.{property.NameUpper});");
                            AppendLine("break;");
                            _indentation--;
                        }
                        EndBlock();
                    }
                    else
                    {
                        AppendLine("props.__invalidated |= propertyName switch");
                        StartBlock();
                        foreach (var property in readableProperties)
                        {
                            AppendLine($"\"{property.Name}\" => Flag({propertyEnumName}.{property.NameUpper}),");
                        }
                        AppendLine("_ => 0");
                        _indentation--;
                        AppendLine("};");
                    }
                    EndBlock(); // while
                    EndBlock(); // if

                    AppendLine("return props;");
                    EndBlock();

                    foreach (var property in writeOnlyProperties)
                    {
                        AppendLine($"{property.DotnetReadType} I{name}Properties.{property.NameUpper} {{ set {{ }} }}");
                    }

                    EndBlock();
                }
            }
        }

